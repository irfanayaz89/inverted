/** Flip Text: turn normal text into upside-down or backwards text you can paste anywhere. */
const MAP: Record<string, string> = {
  a: 'ɐ', b: 'q', c: 'ɔ', d: 'p', e: 'ǝ', f: 'ɟ', g: 'ƃ', h: 'ɥ', i: 'ᴉ', j: 'ɾ', k: 'ʞ', l: 'l', m: 'ɯ',
  n: 'u', o: 'o', p: 'd', q: 'b', r: 'ɹ', s: 's', t: 'ʇ', u: 'n', v: 'ʌ', w: 'ʍ', x: 'x', y: 'ʎ', z: 'z',
  A: '∀', B: 'ᗺ', C: 'Ɔ', D: 'ᗡ', E: 'Ǝ', F: 'Ⅎ', G: '⅁', H: 'H', I: 'I', J: 'ſ', K: 'ʞ', L: '˥', M: 'W',
  N: 'N', O: 'O', P: 'Ԁ', Q: 'Ό', R: 'ᴚ', S: 'S', T: '⊥', U: '∩', V: 'Λ', W: 'M', X: 'X', Y: '⅄', Z: 'Z',
  '1': 'Ɩ', '2': 'ᄅ', '3': 'Ɛ', '4': 'ㄣ', '5': 'ϛ', '6': '9', '7': 'ㄥ', '8': '8', '9': '6', '0': '0',
  '.': '˙', ',': "'", "'": ',', '"': '„', '?': '¿', '!': '¡', '(': ')', ')': '(', '[': ']', ']': '[',
  '{': '}', '}': '{', '<': '>', '>': '<', '&': '⅋', _: '‾',
};

export type FlipMode = 'upside' | 'backwards';
export const MODES: { id: FlipMode; label: string }[] = [
  { id: 'upside', label: 'Upside down' },
  { id: 'backwards', label: 'Backwards' },
];

/** Line order is kept; each line is flipped on its own so pasted text still reads top to bottom. */
export function flipText(text: string, mode: FlipMode): string {
  return text.split('\n').map((line) => {
    const chars = Array.from(line).reverse();
    return (mode === 'upside' ? chars.map((c) => MAP[c] ?? c) : chars).join('');
  }).join('\n');
}
